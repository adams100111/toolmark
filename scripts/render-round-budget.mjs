#!/usr/bin/env node
// Renders the round-budget report (the JSON array `examples/react-vite/e2e/round-budget.spec.ts`
// writes when `ROUND_BUDGET_REPORT` is set) into docs/release/round-budget.md.
//
//   node scripts/render-round-budget.mjs <round-budget.json> [--out <file.md>]
//
// Exits 1 when the report is missing or malformed. Dependencies: Node and git only.
import { execFileSync } from 'node:child_process'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/** Round budget per task (overview "Success criterion 1 in-repo"). */
const BUDGETS = { simple_form: 3, wizard: 5 }

const NUMBER_FIELDS = ['rounds', 'messages', 'manifestBytes', 'describeBytes', 'wallMs']

function budgetOf(task) {
  if (Object.hasOwn(BUDGETS, task)) return BUDGETS[task]
  const prefix = Object.keys(BUDGETS).find((k) => task.startsWith(`${k}_`))
  return prefix ? BUDGETS[prefix] : undefined
}

function commitSha() {
  try {
    return execFileSync('git', ['rev-parse', 'HEAD'], { cwd: repoRoot, encoding: 'utf8' }).trim()
  } catch {
    return 'unknown'
  }
}

function validate(report) {
  if (!Array.isArray(report) || report.length === 0) return 'report must be a non-empty array'
  for (const [i, row] of report.entries()) {
    if (typeof row !== 'object' || row === null) return `entry ${i} is not an object`
    if (typeof row.task !== 'string' || row.task === '')
      return `entry ${i}: "task" must be a string`
    for (const f of NUMBER_FIELDS) {
      if (typeof row[f] !== 'number' || !Number.isFinite(row[f]) || row[f] < 0) {
        return `entry ${i} (${row.task}): "${f}" must be a non-negative number`
      }
    }
  }
  return null
}

async function main() {
  const args = process.argv.slice(2)
  const outIndex = args.indexOf('--out')
  const out =
    outIndex >= 0 && args[outIndex + 1]
      ? resolve(args[outIndex + 1])
      : join(repoRoot, 'docs/release/round-budget.md')
  const input = args.find((a, i) => !a.startsWith('--') && (outIndex < 0 || i !== outIndex + 1))
  if (!input) {
    console.error('usage: node scripts/render-round-budget.mjs <round-budget.json> [--out <file>]')
    return 1
  }
  let report
  try {
    report = JSON.parse(await readFile(resolve(input), 'utf8'))
  } catch (e) {
    console.error(`cannot read ${input}: ${e.message}`)
    return 1
  }
  const problem = validate(report)
  if (problem) {
    console.error(`malformed report ${input}: ${problem}`)
    return 1
  }

  const header = [
    'task',
    'rounds',
    'budget',
    'messages',
    'manifestBytes',
    'describeBytes',
    'wallMs',
  ]
  const body = report.map((r) => {
    const budget = budgetOf(r.task)
    return [
      r.task,
      r.rounds,
      budget === undefined ? '—' : `≤ ${budget}`,
      r.messages,
      r.manifestBytes,
      r.describeBytes,
      r.wallMs,
    ].map(String)
  })
  // Column-aligned like Prettier's Markdown output, so `prettier --check` stays clean.
  const widths = header.map((h, c) => Math.max(3, h.length, ...body.map((row) => row[c].length)))
  const line = (cells) => `| ${cells.map((cell, c) => cell.padEnd(widths[c])).join(' | ')} |`
  const rows = [line(header), line(widths.map((w) => '-'.repeat(w))), ...body.map(line)]
  const date = new Date().toISOString().slice(0, 10)
  const text = [
    '# Round budget',
    '',
    '<!-- Generated by scripts/render-round-budget.mjs from the ROUND_BUDGET_REPORT JSON of',
    '     examples/react-vite/e2e/round-budget.spec.ts. Do not edit by hand; re-render instead. -->',
    '',
    `Commit: \`${commitSha()}\` · Date: ${date} · Browser: Chromium`,
    '',
    ...rows,
    '',
    '## Definitions',
    '',
    '- A scripted in-page agent (no LLM) starts from the first summary `manifest` that lists the',
    "  task's tools (the attach manifest precedes React's registrations) and may `describe`.",
    '  A **round** is one agent turn issuing ≥ 1 tool call (all agent→page messages sent before it',
    '  next awaits results); human confirmation is not a round. Every task asserts zero',
    '  `invalid`/`refused` results.',
    '- `messages`: agent→page messages sent; `manifestBytes`: UTF-8 size of the summary manifest the',
    '  agent started from; `describeBytes`: total UTF-8 size of the `describe` results it received;',
    "  `wallMs`: wall time from the agent's first message to the end of the task.",
    '- Budgets: `simple_form` ≤ 3 rounds (M1), `wizard` ≤ 5 rounds (M2).',
    '',
  ].join('\n')
  await mkdir(dirname(out), { recursive: true })
  await writeFile(out, text)
  console.log(`round budget written to ${out} (${body.length} row(s))`)
  return 0
}

process.exit(await main())
